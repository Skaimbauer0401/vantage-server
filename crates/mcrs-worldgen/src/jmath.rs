//! `java.lang.StrictMath` (fdlibm 5.3) in Rust, bit-exact.
//!
//! HotSpot computes `Math.log/exp/pow/sin/cos` with CPU-specific intrinsics whose
//! results differ between platforms (and from StrictMath in ~2-10% of inputs).
//! mcrs starts the JVM with `-XX:-UseLibmIntrinsic`, which makes `Math.*` use
//! fdlibm exactly like `StrictMath`, so vanilla code and this port agree everywhere.
//!
